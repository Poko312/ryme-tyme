function sqlString(value: string): string {
  return `'${value.replace(/'/g, "''")}'`;
}

function sqlTextArray(values: string[]): string {
  return `array[${values.map(sqlString).join(", ")}]::text[]`;
}

export function buildSeedSql(): string {
  const lines: string[] = [
    "-- GENERATED by scripts/generate-seed.ts — do not edit by hand.",
    "-- Re-generate with: npm run db:seed:generate",
    "",
    "-- Placeholder beats ------------------------------------------------------",
  ];

  PLACEHOLDER_BEATS.forEach((b, i) => {
    lines.push(
      `insert into public.beats (title, producer, bpm, genre, mood, duration_seconds, audio_path, is_premium, is_placeholder, sort_order)`,
      `select ${sqlString(b.title)}, ${sqlString(b.producer)}, ${b.bpm}, ${sqlString(b.genre)}, ${sqlString(b.mood)}, ${b.durationSeconds}, ${sqlString(`/placeholder-beats/${b.file}`)}, ${b.isPremium}, true, ${i}`,
      `where not exists (select 1 from public.beats where audio_path = ${sqlString(`/placeholder-beats/${b.file}`)});`,
    );
  });

  lines.push("", `-- Prompt words (${STARTER_WORDS.length}) ---------------------------------------------`);
  lines.push("insert into public.words (word, difficulty, themes, rhyme_hints) values");
  lines.push(
    STARTER_WORDS.map(
      (w) => `  (${sqlString(w.word)}, ${sqlString(w.difficulty)}, ${sqlTextArray(w.themes)}, ${sqlTextArray(w.rhymeHints)})`,
    ).join(",\n"),
  );
  lines.push("on conflict ((lower(word))) do nothing;", "");
  return lines.join("\n");
}

export { PLACEHOLDER_BEATS };

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = fileURLToPath(new URL("../supabase/seed.sql", import.meta.url));
  writeFileSync(out, buildSeedSql());
  console.log(`Wrote ${out} (${STARTER_WORDS.length} words, ${PLACEHOLDER_BEATS.length} beats)`);
}
